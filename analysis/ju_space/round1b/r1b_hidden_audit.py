"""Bounded exploratory observations of the actual K3a prefill, separate from its tests.

This is cooperative model instrumentation, not debugger-based GPU forensics.
No continuation is generated by the audit; the live decoder supplies its outputs.
"""
import os
import statistics
import time

import r1b_core as RC
from r1b_hidden_capture import COUNTS, FLAG, SCHEMA, PrefillCapture
from r1b_htq_variant import VARIANT, active as htq_active

DIRECTORY = "observations/hidden_states_v1"
LABELS = ["exploratory hidden-state observation", "not a confirmatory test", "cooperative hooks, not GPU debugger acquisition"]


def start_audit(ctx, tok, model, ids_by_family):
    if os.environ.get(FLAG, "0") != "1":
        return None
    if not htq_active(ctx) or ctx.session != "r1b_K_S1":
        raise ValueError("Hidden-state capture is supported only in htq_v2 K_S1/k3a.")
    return HiddenAudit(ctx, tok, model, ids_by_family)


def benchmark_prefill(model, tok, prompts, repetitions=3):
    """Small paired timing/identity check; uncached prefill, not a run-time forecast."""
    import torch
    if model.training:
        raise ValueError("Hidden-state audit requires an eval-mode model.")
    dev = RC.model_device(model)
    ids, mask, _ = RC.pad_left(prompts[:2], tok.pad_token_id)
    ids, mask = ids.to(dev), mask.to(dev)
    pos = (mask.cumsum(-1) - 1).clamp(min=0)

    def sync():
        if torch.device(dev).type == "cuda":
            torch.cuda.synchronize(dev)

    def one(captured):
        observer = PrefillCapture(model, len(ids)) if captured else None
        try:
            sync()
            begun = time.perf_counter()
            with torch.no_grad(), RC.sdpa_efficient(dev):
                if observer is None:
                    out = model(input_ids=ids, attention_mask=mask, position_ids=pos,
                                use_cache=False, logits_to_keep=1)
                else:
                    with observer.setup(0, len(ids)):
                        out = model(input_ids=ids, attention_mask=mask, position_ids=pos,
                                    use_cache=False, logits_to_keep=1)
                        observer.on_fwd(0, 0)
            sync()
            elapsed = time.perf_counter() - begun
            logits = out.logits[:, -1].detach().cpu().clone()
            if observer is not None:
                observer.result()
            return elapsed, logits
        finally:
            if observer is not None:
                observer.close()

    # Warm each path before measuring. No stochastic generation or RNG draw.
    one(False)
    one(True)
    plain, observed, exact = [], [], True
    for i in range(repetitions):
        if i % 2:
            tc, lc = one(True)
            tb, lb = one(False)
        else:
            tb, lb = one(False)
            tc, lc = one(True)
        plain.append(tb)
        observed.append(tc)
        exact = exact and bool(torch.equal(lb, lc))
    baseline, capture = statistics.median(plain), statistics.median(observed)
    return dict(schema=SCHEMA, status="passed" if exact else "failed", logits_exact=exact,
                device=str(dev), requests=len(ids), repetitions=repetitions, warmups_per_path=1,
                baseline_seconds=plain, captured_seconds=observed,
                median_baseline_seconds=baseline, median_captured_seconds=capture,
                ratio=capture / baseline if baseline > 0 else None,
                method="paired uncached prefill, last-token logits; capture transfer included",
                note="Extra diagnostic forwards, no generated answers; not an estimate of whole-run overhead.")


class HiddenAudit:
    def __init__(self, ctx, tok, model, ids_by_family):
        self.ctx, self.tok, self.model = ctx, tok, model
        self.layer_ids = list(range(len(RC.layers_of(model))))
        self.ids = {}
        for family, limit in COUNTS.items():
            ids = [str(q) for q in ids_by_family[family]][:limit]
            if not ids or len(set(ids)) != len(ids):
                raise ValueError(f"Missing or duplicate capture request IDs in {family}.")
            if not ctx.mock and len(ids) != limit:
                raise ValueError(f"Capture requires {limit} preselected {family} requests, found {len(ids)}.")
            self.ids[family] = ids
        self.families = {}
        self.prepared = {}
        self.benchmarked = False
        self.config = dict(schema=SCHEMA, selection="fixed source order, before labels",
                           family_limits=dict(COUNTS), selected_ids=self.ids,
                           layer_ids=self.layer_ids, dtype="float32", token="last real prompt token",
                           hook_location="decoder block output, after residual addition, before final model norm",
                           condition="baseline, no intervention", phase="prefill", forward_step=0,
                           predicts="first generated token", post_hoc=True, h_policy=VARIANT)
        # Replace a previous attempt's complete marker before any new work.
        self._manifest("running")

    def _manifest(self, status):
        obj = dict(schema=SCHEMA, status=status, request_count=sum(f["count"] for f in self.families.values()),
                   planned_count=sum(map(len, self.ids.values())), selected_ids=self.ids,
                   families=self.families, layer_ids=self.layer_ids, dtype="float32",
                   tensor_bytes=sum(f["tensor_bytes"] for f in self.families.values()),
                   condition="baseline, no intervention", capture_kind="live_generation_prefill",
                   exploratory=True, h_policy=VARIANT,
                   benchmark=f"{DIRECTORY}/benchmark.json" if self.benchmarked else None,
                   note="Not a probe result, causal explanation, or replication of GPU-debugger acquisition.")
        self.ctx.write_json(f"{DIRECTORY}/manifest.json", obj, config=self.config, labels=LABELS)

    def prepare(self, family, prompts, keys, max_new):
        if family in self.prepared or family not in self.ids:
            raise ValueError(f"Unexpected or repeated capture family: {family}")
        n = len(self.ids[family])
        if len(prompts) < n or len(keys) != len(prompts) or any(not p for p in prompts[:n]):
            raise ValueError(f"Invalid prompts/keys for capture family {family}.")
        if not self.benchmarked:
            result = benchmark_prefill(self.model, self.tok, prompts[:2])
            self.ctx.write_json(f"{DIRECTORY}/benchmark.json", result, config=self.config, labels=LABELS)
            if not result["logits_exact"]:
                raise RuntimeError("Hidden-state check changed prefill logits; K3a stopped before generation.")
            self.benchmarked = True
            self.ctx.log("Hidden-state prefill check passed; timing saved in observations/hidden_states_v1/benchmark.json.")
        self.prepared[family] = dict(prompts=[list(p) for p in prompts[:n]], keys=list(keys[:n]), max_new=max_new)
        return PrefillCapture(self.model, n)

    def save_family(self, family, capture, prompts, keys, conts, labels, max_new):
        hidden, layer_ids = capture.result()
        n = len(self.ids[family])
        supplied = dict(prompts=[list(p) for p in prompts[:n]], keys=list(keys[:n]), max_new=max_new)
        if family in self.families or self.prepared.get(family) != supplied:
            raise ValueError("Capture request identity changed or family was already saved.")
        if hidden.shape[0] != n or list(layer_ids) != self.layer_ids or len(conts) != len(prompts) or len(labels) != len(prompts):
            raise ValueError("Capture states and generated answers do not align.")
        records = []
        for i, qid in enumerate(self.ids[family]):
            records.append(dict(request_id=f"{family}:{qid}", family=family, question_id=qid,
                                source_index=i, sample_index=0, prompt_token_ids=list(prompts[i]),
                                prompt_length=len(prompts[i]), token_position=len(prompts[i]) - 1,
                                padding="left; captured final column is a real token",
                                generated_token_ids=list(conts[i]), answer_text=self.tok.decode(conts[i]),
                                behavior_label=labels[i], sampling_key=keys[i],
                                generated_tokens_exclude_stop=True, stop_token_id=None,
                                stop_reason="length_limit" if len(conts[i]) == max_new else "stop_token",
                                stop_reason_basis="inferred from decoder continuation length",
                                condition="baseline, no intervention", phase="prefill", forward_step=0))
        obj = dict(schema=SCHEMA, family=family, hidden=hidden, layer_ids=list(layer_ids), records=records,
                   sampling=dict(method="keyed Gumbel-max", temperature=1.0, top_k=50, top_p=0.9, max_new=max_new),
                   config=self.config, exploratory=True)
        rel = f"{DIRECTORY}/{family}.pt"
        path = self.ctx.save_pt(rel, obj, config=self.config, seeds=list(keys[:n]), labels=LABELS)
        self.families[family] = dict(file=rel, count=n, shape=list(hidden.shape), sha256=RC.sha256_file(path),
                                     tensor_bytes=hidden.numel() * hidden.element_size())
        self._manifest("running")

    def finish(self):
        if set(self.families) != set(self.ids) or not self.benchmarked:
            raise ValueError("Hidden-state observation is incomplete.")
        for family, saved in self.families.items():
            path = self.ctx.path(saved["file"])
            if RC.sha256_file(path) != saved["sha256"] or RC.check_output(path):
                raise ValueError(f"Hidden-state artifact failed its integrity check: {family}")
        self._manifest("complete")
        self.ctx.log(f"Hidden-state observation complete: {sum(map(len, self.ids.values()))} requests, {len(self.layer_ids)} layers.")
