def pop_cett(ctx):
    """Answer-token-mean and last-prompt-token CETT of all neurons for the S_fit, S_L and NE (FAB) rows, by teacher forcing K's sample-0
    answers (NE rows without K answers get a greedy 24-token answer, labelled); answer-span mean entropy (UNC+)."""
    tok, model, cf, H, items = setup(ctx)
    rw = refw(ctx, model)
    rows = _rows(items, cf)
    lab_ = []
    miss = [it for it in rows if not it["ans0"]]
    if miss:
        g = E.decode(model, tok, [K.chat_ids(tok, SHORT_QA.format(q=it["question"])) for it in miss], [0] * len(miss), max_new=24, greedy=True)
        for it, r in zip(miss, g):
            it["ans0"] = r["tokens"]; it["span0"] = [0, answer_span(r["tokens"], tok)]
        lab_.append(f"{len(miss)} rows without K answers: greedy answers generated by L")
    prompts = [K.chat_ids(tok, SHORT_QA.format(q=it["question"])) for it in rows]
    seqs = [p + it["ans0"] for p, it in zip(prompts, rows)]
    starts = [len(p) for p in prompts]
    torch = K._torch()

    def wfn(ids, pad, st):
        w = torch.zeros(ids.shape)
        for r in range(ids.shape[0]):
            a, b = rows_b[r]["span0"] if rows_b[r]["span0"] else (0, 0)
            s0 = int(pad[r]) + st[r]
            w[r, s0 + a:s0 + max(b, a + 1)] = 1.0
        return w
    cm, cl, ent = [], [], []
    B = cf["batch"]
    with E.Probe(model, rw, cett_all=True) as pr:
        for i in range(0, len(seqs), B):
            rows_b = rows[i:i + B]

            def run():
                o = E.tf_pass(model, tok, seqs[i:i + B], starts[i:i + B], probe=pr, batch=B, lastpos=True, wpos_fn=wfn)
                ee = []
                for it, x in zip(rows_b, o):
                    a, b = it["span0"] if it["span0"] else (0, 1)
                    lp_prev = x["e"]          # entropy at continuation positions; the producing distribution of token k is at k - 1
                    e_prev = np.concatenate([[np.nan], lp_prev])[a:max(b, a + 1)]
                    ee.append(float(np.nanmean(e_prev)) if np.isfinite(e_prev).any() else float(np.nanmean(x["e"][:max(b, 1)])))
                return dict(cm=torch.stack([x["cmean"] for x in o]).half(), cl=torch.stack([x["clast"] for x in o]).half(), ent=ee)
            r = ctx.cached(f"cett_{i}", run)
            cm.append(r["cm"]); cl.append(r["cl"]); ent += r["ent"]
    save(ctx, "l/cett_rows.pt", dict(ids=[it["id"] for it in rows], split=[it["split"] for it in rows], cls=[it["cls"] for it in rows],
                                     cmean=torch.cat(cm), clast=torch.cat(cl), ent=np.asarray(ent, dtype=np.float32)),
         config=dict(rows=len(rows), prompts_sha256=sha(prompts)), labels=lab_)


def _cett(ctx):
    return loadpt(ctx.path("l/cett_rows.pt"))


def selector(X, y, C, exclude=None):
    """SO-HN selector (K's r1b_hn.select if importable; else L1 logistic by FISTA at C*, positive weights)."""
    try:
        import r1b_hn
        return r1b_hn.select(X, y, C, exclude), "K selector"
    except Exception:
        return S.l1_select(X, y, C, exclude), "L FISTA fallback selector"


def top_set(w, k, X=None, y=None):
    """Top k units by positive weight; if fewer, filled by |weight| of an L2-logistic refit (C = 1, standardised)."""
    w = w.detach().cpu().numpy()
    pos = np.flatnonzero(w > 0)
    sel = pos[np.argsort(-w[pos])][:k].tolist()
    if len(sel) < k and X is not None:
        torch = K._torch()
        Xs = ((X - X.mean(0)) / X.std(0).clamp_min(1e-6))[None]
        W, b = S.logreg(Xs, y[None].float(), torch.ones_like(y[None]).float(), torch.tensor([1.0 / X.shape[0]]))
        order = np.argsort(-np.abs(W[0].cpu().numpy()))
        sel += [int(j) for j in order if int(j) not in sel][:k - len(sel)]
    return sorted(int(j) for j in sel)


def hull(X, members, thr=0.7, exclude=()):
    """Members plus every unit with |r| > thr to a member on the S_fit CETT matrix X [n, N] (partners ordered by max |r|)."""
    if not len(members):
        return [], []
    Xc = X - X.mean(0); sd = Xc.norm(dim=0).clamp_min(1e-9)
    R = (Xc[:, members].T @ Xc) / (sd[members][:, None] * sd[None])          # [m, N]
    mx = R.abs().max(0).values.cpu().numpy()
    mx[members] = -1
    for j in exclude:
        mx[j] = -1
    part = np.flatnonzero(mx > thr)
    part = part[np.argsort(-mx[part])]
    return sorted(set(int(j) for j in members) | set(part.tolist())), part.tolist()


def pop_select(ctx):
    """P (L.1), SEL+ (first unrelated label with |phi| < 0.1 and >= 300 per class, G-sel), UNC+, hulls, CTRL99 (K2's matching rule,
    candidates keyseed('r1bL-CTRL', k), disjoint from P's hull, SEL+ and UNC+) -> L.POP."""
    torch = K._torch()
    tok, model, cf, H, items = setup(ctx)
    L, I = dims(model)
    d = _cett(ctx)
    sp = np.array(d["split"]); cl = np.array(d["cls"])
    fit = np.flatnonzero((sp == "S_fit") & np.isin(cl, ["CC", "CI"]))
    X = d["cmean"][fit].float().to(dev(model)); y = torch.tensor((cl[fit] == "CI").astype(np.float32), device=X.device)
    q = {it["id"]: it for it in items.values()}
    ids = [d["ids"][j] for j in fit]
    lab_ = list(H["labels"])
    P = H["P"]
    if P is None:
        w, sname = selector(X, y, H["C_star"])
        P = sorted(np.flatnonzero(w.cpu().numpy() > 0).tolist())
        lab_.append("P = SO-HN selector on S_fit (no validated H-set)")
    k = len(P)
    hullP, partP = hull(X, P)
    is_hplus = H["P_name"] == "H+"
    # SEL+ label
    cands = [("question starts with 'Who'", lambda it: it["question"].strip().startswith("Who")),
             ("question contains a digit", lambda it: any(ch.isdigit() for ch in it["question"])),
             ("a gold alias contains a digit", lambda it: any(any(ch.isdigit() for ch in a) for a in it["aliases"]))]
    minc = 300 if not ctx.mock else 5
    sel_label, gsel, yl = None, False, None
    for name, f in cands:
        lbl = np.array([1.0 if f(q[i]) else 0.0 for i in ids])
        if min(lbl.sum(), (1 - lbl).sum()) < minc:
            continue
        phi = np.corrcoef(lbl, y.cpu().numpy())[0, 1] if lbl.std() > 0 else 1.0
        if abs(phi) < 0.1:
            sel_label, gsel, yl = name, True, lbl
            break
    def matched(lbl_vec, seed):
        b = S.balance(lbl_vec, seed)
        w, sname = selector(X[b], torch.tensor(lbl_vec[b], device=X.device), H["C_star"])
        st = top_set(w, k, X[b], torch.tensor(lbl_vec[b], device=X.device))
        if is_hplus:
            hs, part = hull(X, st, 0.7 - 1e-9)
            st = (st + [j for j in part if j not in st])[:k]
        return st, sname
    if gsel:
        SEL, sname = matched(yl, 1)
    else:
        SEL, sname = [], None
        lab_.append("G-sel failed (no unrelated selection label)")
    ent = d["ent"][fit]
    yu = np.zeros(len(fit))
    for c in ("CC", "CI"):
        m = cl[fit] == c
        yu[m] = (ent[m] > np.median(ent[m])).astype(float)
    UNC, uname = matched(yu, 2)
    hS, _ = hull(X, SEL) if SEL else ([], [])
    hU, _ = hull(X, UNC)
    forbid = set(hullP) | set(hS) | set(hU)
    # CTRL99 (K2's rule with L's candidate seeds)
    lay = np.bincount(np.asarray(P) // I, minlength=L)
    mc = d["cmean"][fit].float().mean(0).numpy()
    target = mc[P].mean()
    CTRL, k_, tried = [], 0, 0
    pool = [np.setdiff1d(np.arange(l * I, (l + 1) * I), list(forbid)) for l in range(L)]
    while len(CTRL) < cf["n_ctrl"] + 30 and tried < 20000:
        g = np.random.default_rng(ctx.key("r1bL-CTRL", k_)); k_ += 1; tried += 1
        s = np.concatenate([g.choice(pool[l], lay[l], replace=False) for l in range(L) if lay[l]]).tolist()
        if abs(mc[s].mean() - target) <= 0.2 * abs(target):
            CTRL.append(sorted(int(j) for j in s))
    if len(CTRL) < cf["n_ctrl"] + 25:
        lab_.append(f"only {len(CTRL)} matched random sets (CTRL99 + L3b / L4 / X reserves)")
    pop = dict(P=P, P_name=H["P_name"], H_tq=H["H_tq"], Htq_extra=H["H_tq"] if is_hplus else [], SEL=SEL, UNC=UNC, SEL_label=sel_label,
               G_sel=gsel, CTRL=CTRL[:cf["n_ctrl"]], CTRL_reserve=CTRL[cf["n_ctrl"]:], boot=H["boot"][:cf["n_boot_sets"]],
               hull_P=hullP, partners_P=partP, hull_SEL=hS, hull_UNC=hU, layer_counts=lay.tolist(), target_cett=float(target),
               sg8_ok=H["sg8_ok"], sg8_preview=H["sg8_preview"], H_op_name=H["H_op_name"], selector=sname or uname, n_candidates=k_,
               labels=lab_)
    wj(ctx, "l/l_pop.json", pop, config=dict(n_ctrl=cf["n_ctrl"], rule="K2 matching: same count per layer, mean answer-CETT +-20 %",
                                             seeds="keyseed('r1bL-CTRL', k)", C_star=H["C_star"]), labels=lab_)


