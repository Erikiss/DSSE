    # pre-answer
    pre = pip["pre"]
    st["pre"] = {m: float(np.median(S.ihat(pre["U"][i]).numpy())) for i, m in enumerate(pre["grid"])}
    st["pre_floor"] = {m: float(np.quantile(S.ihat(pre["floor"][i]).numpy(), 0.95)) for i, m in enumerate(pre["floor_grid"])}
    # selection robustness on the boot sets
    if len(rs["boot_loss"]) >= 10:
        Ib = S.ihat(rs["boot_loss"]).numpy()
        st["boot_priv_n"] = int(sum(K.p_rank(x, IM) <= 0.01 + 1e-12 and x > F.get(mP, 0) for x in Ib))
        st["sel_robust"] = st["boot_priv_n"] >= 16 if Priv else None
    else:
        st["sel_robust"] = None
    st["Lambda_max"] = lam_max
    flags = dict(Priv=Priv, rho2=st["rho2"], R_rep=st["R_rep"], xh_ratio=st["xh_ratio"], Ihat_P=st["Ihat_P"], I_ref=dict(pt=Iref),
                 medU1024=st["medU1024"], m0=m0, syn=st["syn"], mono=st["mono"], red=st["red"], Lambda=lam_max, basis_np=st["basis_np"],
                 sel_robust=st["sel_robust"], falsified=st["falsified"])
    st["tree_input"] = flags
    st["cal_ok"] = bool(st["l1c"]["ok"].get("localist") and st["l1c"]["ok"].get("redundant") and st["l1c"]["ok"].get("dense"))
    # erasure
    era = loadpt(ctx.path("l/l1_era.pt")); cal = K.load_json(ctx.path("l/l1_era_cal.json"))
    cls = np.array(era["cls"]); o = era["out"]
    rate = lambda c, m, key: float(np.mean(np.array(o[c][key])[m])) if m.any() else float("nan")
    cc, ci, fab = cls == "CC", cls == "CI", cls == "NE"
    fr = cf["era_fr"]
    curve = [rate("base", cc, "correct")] + [float(np.mean([rate(f"mean_f{f:.6g}_d{d}", cc, "correct") for d in range(cf["era_draws"])]))
                                              for f in fr]
    wrong = lambda c: (~np.array(o[c]["correct"]) & ~np.array(o[c]["refusal"])).astype(float)
    nonref = lambda c: (~np.array(o[c]["refusal"])).astype(float)
    sets = [k for k in o if k.startswith("R")]
    i_ci, i_fab = np.flatnonzero(ci), np.flatnonzero(fab)
    B2 = cf["nboot"]
    g = np.random.default_rng(7)

    def two_level(fn_rows, idx):
        P_ = fn_rows("P")[idx]; R_ = np.stack([fn_rows(s)[idx] for s in sets]) if sets else np.zeros((1, len(idx)))
        ptv = P_.mean() - R_.mean()
        dr = []
        for _ in range(B2):
            ii = g.integers(0, len(idx), len(idx)); ss = g.integers(0, len(R_), len(R_))
            dr.append(P_[ii].mean() - R_[ss][:, ii].mean())
        return S.summ(ptv, dr, margin=0.05)
    era_st = dict(cc_acc_curve=curve, sizes=fr, diff_ci_wrong=two_level(wrong, i_ci) if len(i_ci) else None,
                  diff_fab_nonref=two_level(nonref, i_fab) if len(i_fab) else None, g_dmg=cal["g_dmg"],
                  rates={c: dict(cc_acc=rate(c, cc, "correct"), ci_wrong=float(wrong(c)[ci].mean()) if ci.any() else None,
                                 refusal=float(np.mean(o[c]["refusal"])), fab_nonref=float(nonref(c)[fab].mean()) if fab.any() else None,
                                 dlogq_cc=float(np.mean(o[c]["lpgold"]) - np.mean(o["base"]["lpgold"]))) for c in o},
                  damage=dict(P=cal["P"], sets={k: dict(damage=v["damage"], in_band=v["in_band"], damage_U32=v["damage_U32"])
                                                for k, v in cal["sets"].items()}))
    st["erasure"] = era_st
    wj(ctx, "l/l1.json", st, config=dict(nboot=cf["nboot"], grid=grid, P_name=pop["P_name"]),
       labels=pop["labels"] + ([] if st["cal_ok"] else ["L1-C calibration failed"]))


