def _era_items(items, cf):
    return split_rows(items, "S_L") + split_rows(items, "NE")


def era_conditions(ctx, pop, N, cf):
    """Nested random fragments (3 draws, seed 'r1bL-ERA'), P (+ H_tq / H+ if they differ), 8 CTRL99 sets 13-20, zero ablation at 2^-8
    and 2^-4 (draw 0)."""
    conds = []
    for dr in range(cf["era_draws"]):
        perm = rng("r1bL-ERA", dr).permutation(N)
        for f in cf["era_fr"]:
            conds.append(dict(name=f"mean_f{f:.6g}_d{dr}", ids=sorted(perm[:max(1, int(round(f * N)))].tolist()), kind="mean", lam=0.0))
            if dr == 0 and f in (cf["era_fr"][len(cf["era_fr"]) // 2], cf["era_fr"][-1]):
                conds.append(dict(name=f"zero_f{f:.6g}_d0", ids=sorted(perm[:max(1, int(round(f * N)))].tolist()), kind="zero"))
    conds.append(dict(name="P", ids=pop["P"], kind="mean", lam=0.0))
    for nm, s in (("H_tq", pop["H_tq"]), ("Hplus", None)):
        if s and sorted(s) != sorted(pop["P"]):
            conds.append(dict(name=nm, ids=s, kind="mean", lam=0.0))
    base = 12 if len(pop["CTRL"]) >= 20 else 0
    for j in range(cf["era_sets"]):
        k = min(base + j, len(pop["CTRL"]) - 1)
        conds.append(dict(name=f"R{k}", ids=pop["CTRL"][k], kind="mean", lam=None, ctrl=k))
    return conds


def l1_era_cal(ctx):
    """Damage of P's mean ablation; the 8 random sets damage-matched within +-10 % by partial mean ablation z <- mu + lam (z - mu), lam
    calibrated in SO-DMG's gain form on (1 - lam) (part-file amendment: gain form, <= 6 evaluations); a set whose full ablation is below
    P's damage is doubled (a second matched draw added, frozen fallback)."""
    tok, model, cf, H, items = setup(ctx)
    rw = refw(ctx, model)
    pop = load_pop(ctx)
    refL, refU, rl = ref_sets(ctx, tok, items, cf)
    dm, du = K.Damage(model, refL), K.Damage(model, refU)
    L, I = dims(model)

    def dmg(ids, lam, D=dm):
        def setup_():
            pr = E.Probe(model, rw); pr.add_op(ids, "mean", lam=lam)
            return _ProbeCM(pr)
        return D(setup_)["damage"]
    dP = dmg(pop["P"], 0.0)
    res = dict(P=dict(damage=dP, damage_U32=dmg(pop["P"], 0.0, du)), sets={}, labels=rl)
    for c in era_conditions(ctx, pop, L * I, cf):
        if "ctrl" not in c:
            continue
        ids = c["ids"]; extra = []
        full = dmg(ids, 0.0)
        if full < dP * 0.9:
            g = np.random.default_rng(ctx.key("r1bL-CTRL", "dbl", c["ctrl"]))
            lay = np.bincount(np.asarray(ids) // I, minlength=L)
            extra = np.concatenate([g.choice(np.setdiff1d(np.arange(l * I, (l + 1) * I), ids), lay[l], replace=False)
                                    for l in range(L) if lay[l]]).tolist()
            ids = sorted(set(ids) | set(extra)); full = dmg(ids, 0.0)
        cal = K.calibrate(lambda a: dmg(ids, 1.0 - a), 1.0, dP, form="gain", max_eval=6, cap=1.0)
        res["sets"][c["name"]] = dict(ids=ids, doubled=bool(extra), full_damage=full, lam=1.0 - cal["f"], damage=cal["damage"],
                                      in_band=cal["in_band"], labels=cal["labels"], tried=cal["tried"],
                                      damage_U32=dmg(ids, 1.0 - cal["f"], du))
    res["g_dmg"] = all(v["in_band"] for v in res["sets"].values())
    wj(ctx, "l/l1_era_cal.json", res, config=dict(target="P mean-ablation damage", band=0.10, form="gain on 1 - lambda, <= 6 evaluations"),
       labels=rl + ([] if res["g_dmg"] else ["G-dmg failed"]))


class _ProbeCM:
    def __init__(self, pr):
        self.pr = pr

    def __enter__(self):
        return self.pr

    def __exit__(self, *a):
        self.pr.remove()


def l1_era(ctx):
    """Erasure runs: greedy <= 24 tokens on the S_L and FAB rows under every condition (plus the unablated baseline); CC accuracy, CI
    wrong-answer rate, refusal rate, FAB non-refusal rate, teacher-forced Delta log q(answer) on CC."""
    torch = K._torch()
    tok, model, cf, H, items = setup(ctx)
    rw = refw(ctx, model)
    pop = load_pop(ctx)
    L, I = dims(model)
    cal = K.load_json(ctx.path("l/l1_era_cal.json"))
    rows = _era_items(items, cf)
    alias, refusal, sname = scorers()
    prompts = [K.chat_ids(tok, SHORT_QA.format(q=it["question"])) for it in rows]
    conds = [dict(name="base", ids=None)] + era_conditions(ctx, pop, L * I, cf)
    out = {}
    for c in conds:
        def run():
            pr = E.Probe(model, rw)
            if c.get("ids") is not None:
                if "ctrl" in c:
                    s = cal["sets"][c["name"]]; pr.add_op(s["ids"], "mean", lam=s["lam"])
                else:
                    pr.add_op(c["ids"], c["kind"], lam=c.get("lam"))
            try:
                gen = []
                for i in range(0, len(prompts), 4 * cf["batch"]):
                    gen += E.decode(model, tok, prompts[i:i + 4 * cf["batch"]], [0] * len(prompts[i:i + 4 * cf["batch"]]),
                                    max_new=cf["era_new"], greedy=True)
                cc = [j for j, it in enumerate(rows) if it["cls"] == "CC"]
                tf = E.tf_pass(model, tok, [prompts[j] + rows[j]["ans0"] for j in cc], [len(prompts[j]) for j in cc], batch=cf["batch"])
            finally:
                pr.remove()
            txt = [tok.decode(gx["tokens"]) for gx in gen]
            return dict(correct=[bool(alias(t, it["aliases"])) for t, it in zip(txt, rows)], refusal=[bool(refusal(t)) for t in txt],
                        lpgold=[float(np.nanmean(x["lp"])) for x in tf])
        out[c["name"]] = ctx.cached(f"era_{c['name']}", run, fmt="json")
    save(ctx, "l/l1_era.pt", dict(out=out, cls=[it["cls"] for it in rows], ids=[it["id"] for it in rows],
                                  conds=[dict(name=c["name"], n=len(c["ids"]) if c.get("ids") else 0) for c in conds]),
         config=dict(new=cf["era_new"], scorers=sname, prompts_sha256=sha(prompts)), labels=[sname])


